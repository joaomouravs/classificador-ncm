"""Every model's scores as a file in results/, and REPORT.md built from those files.

The models train in different places (a laptop for the baselines, Kaggle for BERTimbau,
an API for the LLM), so each writes the same small JSON, and the comparison is only ever
made from those files.
"""

from __future__ import annotations

import json
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pandas as pd

from ncm.evaluate import score

RESULTS = Path("results")


def record(
    name: str,
    predict: Callable[[list[str]], list[str]],
    splits: dict[str, pd.DataFrame],
    labels: list[str],
    details: dict[str, Any],
    results: Path = RESULTS,
) -> dict[str, Any]:
    test = splits["test"]["text"].tolist()
    start = time.perf_counter()
    predicted = predict(test)
    seconds = time.perf_counter() - start
    document = {
        "model": name,
        **details,
        "ms_per_1000_items": round(1000 * seconds / max(1, len(test)) * 1000, 1),
        "validation": score(
            splits["validation"]["label"].tolist(),
            predict(splits["validation"]["text"].tolist()),
            labels,
        ).as_dict(),
        "test": score(splits["test"]["label"].tolist(), predicted, labels).as_dict(),
    }
    results.mkdir(parents=True, exist_ok=True)
    (results / f"{name}.json").write_text(
        json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    return document


def build_report(results: Path = RESULTS) -> str:
    documents = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(results.glob("*.json"))]
    documents.sort(key=lambda d: -d["test"]["macro_f1"])
    lines = [
        "# Results",
        "",
        "Generated by `ncm report` from `results/*.json`. Test is the descriptions first",
        "seen on the last collected day; see the dataset card for the splits.",
        "",
        "| Model | Test macro-F1 | Test accuracy | Validation macro-F1 | Time per 1,000 items |",
        "| --- | --: | --: | --: | --: |",
    ]
    for d in documents:
        lines.append(
            f"| {d['model']} | {d['test']['macro_f1']:.3f} | {d['test']['accuracy']:.3f} "
            f"| {d['validation']['macro_f1']:.3f} | {d['ms_per_1000_items'] / 1000:.2f}s |"
        )
    for d in documents:
        lines += [
            "",
            f"## {d['model']}",
            "",
            "| Chapter | Precision | Recall | F1 | Test examples |",
            "| --- | --: | --: | --: | --: |",
        ]
        for label, c in d["test"]["per_class"].items():
            lines.append(
                f"| {label} | {c['precision']:.2f} | {c['recall']:.2f} | {c['f1']:.2f} "
                f"| {c['support']} |"
            )
        if d["test"]["confusions"]:
            pairs = ", ".join(f"{t} as {p} ({n})" for t, p, n in d["test"]["confusions"][:5])
            lines += ["", f"Most common mistakes: {pairs}."]
    return "\n".join(lines) + "\n"
