"""Every model's scores as a file in results/, and REPORT.md built from those files.

The models train in different places (a laptop for the baselines, Kaggle for BERTimbau,
an API for the LLM), so each writes the same small JSON, and the comparison is only ever
made from those files. Each file keeps its test predictions too: the LLM only sees a
sample of the test set, and every other model is also scored on that same sample.
"""

from __future__ import annotations

import json
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pandas as pd

from ncm.evaluate import score

RESULTS = Path("results")


def record(
    name: str,
    predict: Callable[[list[str]], list[str]],
    splits: dict[str, pd.DataFrame],
    labels: list[str],
    details: dict[str, Any],
    results: Path = RESULTS,
) -> dict[str, Any]:
    test = splits["test"]["text"].tolist()
    start = time.perf_counter()
    predicted = predict(test)
    seconds = time.perf_counter() - start
    document = {
        "model": name,
        **details,
        "ms_per_1000_items": round(1000 * seconds / max(1, len(test)) * 1000, 1),
        "validation": score(
            splits["validation"]["label"].tolist(),
            predict(splits["validation"]["text"].tolist()),
            labels,
        ).as_dict(),
        "test": score(splits["test"]["label"].tolist(), predicted, labels).as_dict(),
        "test_predictions": predicted,
    }
    save(document, results)
    return document


def save(document: dict[str, Any], results: Path = RESULTS) -> None:
    results.mkdir(parents=True, exist_ok=True)
    (results / f"{document['model']}.json").write_text(
        json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )


def _on_sample(documents: list[dict[str, Any]], labels: list[str]) -> list[str]:
    """Every model scored on the test rows the LLM saw, so the comparison is like for
    like. Empty when no model ran on a sample, or the sample is the whole test set."""
    sampled = next((d for d in documents if "sample" in d), None)
    if sampled is None or len(sampled["sample"]["indices"]) == sampled["sample"]["of"]:
        return []
    indices, truth = sampled["sample"]["indices"], sampled["sample"]["labels"]
    rows = []
    for d in documents:
        if d is sampled:
            predicted = d["test_predictions"]
        elif len(d.get("test_predictions", [])) == sampled["sample"]["of"]:
            predicted = [d["test_predictions"][i] for i in indices]
        else:
            continue
        s = score(truth, predicted, labels)
        rows.append((s.macro_f1, f"| {d['model']} | {s.macro_f1:.3f} | {s.accuracy:.3f} |"))
    rows.sort(key=lambda r: -r[0])
    return [
        "",
        f"## On the LLM's sample ({len(indices):,} of {sampled['sample']['of']:,} test items)",
        "",
        "| Model | Macro-F1 | Accuracy |",
        "| --- | --: | --: |",
        *(r[1] for r in rows),
    ]


def build_report(results: Path = RESULTS) -> str:
    documents = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(results.glob("*.json"))]
    documents.sort(key=lambda d: -d["test"]["macro_f1"])
    labels = list(documents[0]["test"]["per_class"]) if documents else []
    lines = [
        "# Results",
        "",
        "Generated by `ncm report` from `results/*.json`. Test is the descriptions first",
        "seen on the last collected day; see the dataset card for the splits.",
        "",
        "| Model | Test items | Test macro-F1 | Test accuracy | Validation macro-F1 "
        "| Time per 1,000 items |",
        "| --- | --: | --: | --: | --: | --: |",
    ]
    for d in documents:
        validation = f"{d['validation']['macro_f1']:.3f}" if d.get("validation") else "n/a"
        lines.append(
            f"| {d['model']} | {d['test']['examples']:,} | {d['test']['macro_f1']:.3f} "
            f"| {d['test']['accuracy']:.3f} | {validation} "
            f"| {d['ms_per_1000_items'] / 1000:.2f}s |"
        )
    lines += _on_sample(documents, labels)
    for d in documents:
        lines += [
            "",
            f"## {d['model']}",
            "",
            "| Chapter | Precision | Recall | F1 | Test examples |",
            "| --- | --: | --: | --: | --: |",
        ]
        for label, c in d["test"]["per_class"].items():
            lines.append(
                f"| {label} | {c['precision']:.2f} | {c['recall']:.2f} | {c['f1']:.2f} "
                f"| {c['support']} |"
            )
        if d["test"]["confusions"]:
            pairs = ", ".join(f"{t} as {p} ({n})" for t, p, n in d["test"]["confusions"][:5])
            lines += ["", f"Most common mistakes: {pairs}."]
    return "\n".join(lines) + "\n"
